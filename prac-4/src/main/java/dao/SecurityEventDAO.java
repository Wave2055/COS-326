package dao;

import com.mongodb.client.MongoCollection;
import com.mongodb.client.model.Filters;
import com.mongodb.client.model.Updates;
import com.mongodb.client.result.UpdateResult;
import db.MongoConnection;
import model.SecurityEvent;
import model.SeveritySummaryRow;
import org.bson.Document;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;

/**
 * All MongoDB access used by the SOC application. Every result is read from
 * the database - nothing is cached or hard-coded.
 */
public class SecurityEventDAO {

    public static final List<String> SEVERITY_LEVELS =
            Arrays.asList("Low", "Medium", "High", "Critical");

    private MongoCollection<Document> collection() {
        return MongoConnection.getDatabase()
                .getCollection(MongoConnection.COLLECTION_NAME);
    }

    /**
     * Question 3.3 - retrieves every security event generated by the supplied
     * source IP address.
     */
    public List<SecurityEvent> findBySourceIP(String sourceIP) {
        List<SecurityEvent> events = new ArrayList<>();

        for (Document document : collection().find(Filters.eq("sourceIP", sourceIP))) {
            events.add(new SecurityEvent(document));
        }
        return events;
    }

    /** Retrieves every security event, used to populate the initial view. */
    public List<SecurityEvent> findAll() {
        List<SecurityEvent> events = new ArrayList<>();

        for (Document document : collection().find()) {
            events.add(new SecurityEvent(document));
        }
        return events;
    }

    /**
     * Question 3.4 - updates the severity of the event with the supplied event ID.
     *
     * @return the number of documents that were modified.
     */
    public long updateSeverity(String eventId, String newSeverity) {
        UpdateResult result = collection().updateOne(
                Filters.eq("eventId", eventId),
                Updates.set("severity", newSeverity));

        return result.getModifiedCount();
    }

    /** Returns true when an event with the supplied ID exists. */
    public boolean eventExists(String eventId) {
        return collection().countDocuments(Filters.eq("eventId", eventId)) > 0;
    }

    /**
     * Question 3.5 - aggregation pipeline returning the number of security
     * events at each severity level, highest count first.
     */
    public List<SeveritySummaryRow> getSeveritySummary() {
        List<Document> pipeline = Arrays.asList(
                new Document("$group", new Document("_id", "$severity")
                        .append("numberOfEvents", new Document("$sum", 1))),
                new Document("$project", new Document("_id", 0)
                        .append("severity", "$_id")
                        .append("numberOfEvents", 1)),
                new Document("$sort", new Document("numberOfEvents", -1)));

        List<SeveritySummaryRow> summary = new ArrayList<>();
        for (Document document : collection().aggregate(pipeline)) {
            summary.add(new SeveritySummaryRow(
                    document.getString("severity"),
                    document.getInteger("numberOfEvents", 0)));
        }
        return summary;
    }
}
