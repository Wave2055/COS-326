/** Resolves a collection handle from a database name and collection name. */
function _collection(dbName, colName) {
    if (!dbName || !colName) {
        throw new Error("A database name and a collection name are required.");
    }
    return db.getSiblingDB(dbName).getCollection(colName);
}

/**
 * Builds the next unique event ID for the collection.
 * Existing IDs follow the EVT#### pattern, so the highest number is extended.
 */
function _nextEventNumber(col) {
    const highest = col.find(
        { eventId: /^EVT[0-9]+$/ },
        { eventId: 1, _id: 0 }
    ).sort({ eventId: -1 }).limit(1).toArray();

    if (highest.length === 0) {
        return 10001;
    }
    return parseInt(highest[0].eventId.substring(3), 10) + 1;
}

/** Returns a random element of the supplied array. */
function _pick(values) {
    return values[Math.floor(Math.random() * values.length)];
}

/** Builds a random private IPv4 address. */
function _randomIP(prefix) {
    return prefix + "." + Math.floor(Math.random() * 256) + "." + Math.floor(Math.random() * 254 + 1);
}

