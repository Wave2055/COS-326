/**
 * Question 1.2 - Inserts `count` generated security event documents into the
 * given collection. Each document receives a unique event ID.
 */
function insertSecurityEvents(dbName, colName, count) {
    const col = _collection(dbName, colName);

    if (typeof count !== "number" || !Number.isInteger(count) || count < 1) {
        print("The number of events to insert must be a positive whole number.");
        return;
    }

    const eventTypes = [
        "Brute Force Attack", "Malware Detection", "Port Scan",
        "Phishing Attempt", "SQL Injection Attempt", "Data Exfiltration",
        "Suspicious Login", "Firewall Rule Violation"
    ];
    const severities = ["Low", "Medium", "High", "Critical"];
    const sources = [
        "Firewall", "Network IDS", "Endpoint Security",
        "Authentication Server", "Web Application Firewall", "Email Security Gateway"
    ];

    let nextNumber = _nextEventNumber(col);
    const documents = [];

    for (let i = 0; i < count; i++) {
        const eventType = _pick(eventTypes);
        const severity = _pick(severities);

        documents.push({
            eventId: "EVT" + (nextNumber + i),
            timestamp: new Date().toISOString().substring(0, 19) + "Z",
            sourceIP: _randomIP("192.168"),
            destinationIP: _randomIP("10.0"),
            eventType: eventType,
            severity: severity,
            description: "Generated " + severity.toLowerCase() + " severity " +
                eventType.toLowerCase() + " recorded by the SOC monitoring pipeline.",
            source: _pick(sources)
        });
    }

    const result = col.insertMany(documents);
    const inserted = Object.keys(result.insertedIds).length;

    print(inserted + " security event document(s) were inserted into " +
        dbName + "." + colName + ".");
}

/**
 * Question 1.3 - Retrieves and prints every security event generated by the
 * supplied source IP address.
 */
function findEventsByIP(dbName, colName, sourceIP) {
    const col = _collection(dbName, colName);

    if (!sourceIP) {
        print("A source IP address is required.");
        return;
    }

    const matches = col.find({ sourceIP: sourceIP }).toArray();

    if (matches.length === 0) {
        print("No security events were found for source IP " + sourceIP + ".");
        return;
    }

    print(matches.length + " security event(s) found for source IP " + sourceIP + ":");
    matches.forEach(function (event) {
        printjson(event);
    });
}

/**
 * Question 1.4 - Updates the severity of every security event matching the
 * supplied event type.
 */
function updateSeverity(dbName, colName, eventType, newSeverity) {
    const col = _collection(dbName, colName);

    if (!eventType || !newSeverity) {
        print("An event type and a new severity are required.");
        return;
    }

    const allowed = ["Low", "Medium", "High", "Critical"];
    if (allowed.indexOf(newSeverity) === -1) {
        print("Severity must be one of: " + allowed.join(", ") + ".");
        return;
    }

    const result = col.updateMany(
        { eventType: eventType },
        { $set: { severity: newSeverity } }
    );

    if (result.matchedCount === 0) {
        print("No security events of type \"" + eventType + "\" were found.");
        return;
    }

    print(result.modifiedCount + " security event document(s) of type \"" +
        eventType + "\" were updated to severity " + newSeverity + ".");
}

/**
 * Question 1.5 - Removes every security event whose severity is Low.
 */
function removeLowSeverityEvents(dbName, colName) {
    const col = _collection(dbName, colName);

    const result = col.deleteMany({ severity: "Low" });

    print(result.deletedCount + " low severity security event document(s) were removed from " +
        dbName + "." + colName + ".");
}

