/**
 * Question 2.4 - Aggregation pipeline summarising the number of security
 * events recorded at each severity level, highest count first.
 */
function securityEventSummary(dbName, colName) {
    const col = _collection(dbName, colName);

    const results = col.aggregate([
        { $group: { _id: "$severity", numberOfEvents: { $sum: 1 } } },
        { $project: { _id: 0, severity: "$_id", numberOfEvents: 1 } },
        { $sort: { numberOfEvents: -1 } }
    ]).toArray();

    print("SECURITY EVENT SUMMARY");
    results.forEach(function (row) {
        printjson(row);
    });
}

/**
 * Question 2.5 - Creates the description text index (if required) and performs
 * a text search for the supplied term.
 */
function searchEventDescriptions(dbName, colName, searchTerm) {
    const col = _collection(dbName, colName);

    if (!searchTerm) {
        print("A search term is required.");
        return;
    }

    col.createIndex({ description: "text" });

    const results = col.find(
        { $text: { $search: searchTerm } },
        { _id: 0, eventId: 1, eventType: 1, severity: 1, description: 1 }
    ).toArray();

    if (results.length === 0) {
        print("No security event descriptions contain \"" + searchTerm + "\".");
        return;
    }

    print(results.length + " security event(s) matching \"" + searchTerm + "\":");
    results.forEach(function (event) {
        printjson(event);
    });
}
