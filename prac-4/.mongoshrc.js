/**
 * Question 2.1 - Retrieves all High and Critical security events, sorted by
 * timestamp in descending order.
 */
function findHighAndCriticalEvents(dbName, colName) {
    const col = _collection(dbName, colName);

    const results = col.find(
        { severity: { $in: ["High", "Critical"] } },
        { _id: 0, eventId: 1, timestamp: 1, sourceIP: 1, eventType: 1, severity: 1 }
    ).sort({ timestamp: -1 }).toArray();

    print(results.length + " High/Critical security event(s):");
    results.forEach(function (event) {
        printjson(event);
    });
}

